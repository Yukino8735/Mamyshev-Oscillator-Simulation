function fixture = gain_rollback_fixture()
%GAIN_ROLLBACK_FIXTURE Artificial deterministic single-step test, not a design.
% Tiny grid and disabled Raman are fixture-only; production defaults are intact.
N = 32;
dt = 0.05; % ps
t = ((-N/2):(N/2-1))'*dt;
sim = struct('gpu_yes',false,'single_yes',false,'scalar',true,...
    'Raman_model',0,'Raman_sponRS',false,'SK_factor',1,'f0',290,...
    'pulse_centering',false,'progress_bar',false,'save_period',0.002,...
    'deltaZ',0.001,'last_deltaZ',1);
sim.adaptive_deltaZ = struct('model',true,'max_deltaZ',0.01,'threshold',1e-6);
gain = struct('reuse_data',false,'linear_oscillator_model',0,...
    'save_all_in_RAM',false,'copump_power',4,'counterpump_power',0,...
    'ignore_ASE',true,'export_N2',true,'midx',1,'pump_direction','co',...
    'core_diameter',10,'pump_wavelength',976,'t_rep',40e-9,'tau',840e-6,...
    'verbose',false,'tol',1e-6,'max_iterations',4);
initial = struct('dt',dt,...
    'fields',ifft(sqrt(10)*exp(-(t/0.25).^2).*exp(0.1i*(t/0.25).^2)));
omega = 2*pi*ifftshift(((-N/2):(N/2-1))'/(N*dt));
cross_pump = struct('absorption',2e-12,'emission',1e-12); % um^2
cross_signal = struct('absorption',reshape(ones(N,1)*1e-13,[1 1 1 1 N]),...
    'emission',reshape(ones(N,1)*2e-13,[1 1 1 1 N]));
overlap = struct('pump',1/(pi*(125/2)^2),'signal',1/(pi*(10/2)^2));
SRa = struct('SRa',1,'nonzero_midx1234s',ones(4,1),'nonzero_midx34s',ones(2,1));
fixture = struct('sim',sim,'gain',gain,'initial',initial,'omegas',omega,...
    'cross_pump',cross_pump,'cross_signal',cross_signal,'overlap',overlap,...
    'N_total',9e7,'FmFnN',9e7,'GammaN',9e7,'prefactor',1i*0.01,...
    'D_op',1i*0.01*omega.^2,'SK_info',[],'SRa_info',SRa,'SRb_info',[],...
    'haw',[],'hbw',[],'sponRS_prefactor',{{}},'dummy',zeros(N,1));
end
