function report=test_stationarity_analysis(output_dir)
% Explicit artificial intensities and saved-field fixtures, no propagation.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(root,'scripts')); addpath(fullfile(root,'code','ml_bridge'));
N=64; dt=0.125; reference=zeros(N,1); reference(20:24)=[1;3;8;3;1];
saved_rng=rng; cases=struct('name',{},'passed',{});
[same,aligned]=mamyshev_intensity_alignment(reference,reference,dt);
check('identical_intensity_no_shift_no_difference',same.shift_samples==0 && ...
    same.raw_relative_L2==0 && same.aligned_relative_L2==0 && ~same.ambiguous && isequal(aligned,reference));
shifted=circshift(reference,9);
[translation,aligned]=mamyshev_intensity_alignment(shifted,reference,dt);
check('known_integer_whole_window_shift_recovered',translation.shift_samples==-9 && ...
    translation.shift_ps==-9*dt && translation.raw_relative_L2>0 && translation.aligned_relative_L2==0 && isequal(aligned,reference));
deformed=zeros(N,1); deformed(20:24)=[2;4;4;4;2];
shape=mamyshev_intensity_alignment(deformed,reference,dt);
check('equal_energy_shape_change_remains_after_alignment',sum(deformed)==sum(reference) && shape.aligned_relative_L2>0.1);
multiple=zeros(N,1); multiple([10 42])=1;
ambiguity=mamyshev_intensity_alignment(multiple,multiple,dt);
near=multiple; near(42)=1-1e-5; near_ambiguity=mamyshev_intensity_alignment(near,near,dt);
flat=mamyshev_intensity_alignment(ones(N,1),ones(N,1),dt);
check('multiple_peaks_near_equal_peaks_and_constant_ambiguity',ambiguity.ambiguous && ...
    ambiguity.shift_samples==0 && ambiguity.tie_lag_count==2 && ...
    near_ambiguity.ambiguous && near_ambiguity.tie_lag_count==1 && ...
    flat.ambiguous && flat.shift_samples==0 && flat.tie_lag_count==N);

% Periodic half-maximum region crosses the original first/last samples.
power=zeros(N,1); power([63 64 1 2 3])=[5;6;8;6;5];
t=((0:N-1)-N/2)*dt; f0=3; f=f0+((0:N-1)'-N/2)/(N*dt);
identity=struct('run_id','synthetic_stationarity','source_identity',struct('fixture','stationarity_v1'));
design=struct('kind','artificial_periodic_intensity','not_a_physical_design',true);
fixture_dir=fullfile(output_dir,'stationarity_fixture'); mkdir(fixture_dir);
writer=MamyshevWaveforms(fixture_dir,identity,design); writer.initialize(t,f,f0);
for k=1:6
    pre=sqrt(circshift(power,k-1)); post=sqrt(power);
    energy=trapz(t,abs(pre).^2)/1000; writer.round(k,pre,post,energy);
end
legacy=struct('output_field',post,'pigtail_output_field',post,'output_energy',energy,'rt_num',6, ...
    't',t,'f',f,'fwhm_ps',t(end)-t(1),'dechirped_peak_power_W',16, ...
    'dechirped_fwhm_fs',50,'transform_limited_fwhm_fs',40,'energy_rel_fluct',0.1, ...
    'converged',true,'force_stop',false,'pulse_survives',true,'ML_state',1);
writer.finish(legacy,sqrt(2)*post); legacy.compressed_field=sqrt(2)*post;
provenance=struct('run_id',identity.run_id,'source_identity',identity.source_identity, ...
    'physics_identity_id','synthetic_stationarity','numerical_version','fixture_only','source_kind','synthetic_component_fixture');
write_mamyshev_record(fullfile(fixture_dir,'final_result.json'), ...
    mamyshev_result_record(legacy,struct('job_status','completed'),provenance));
analysis=analyze_mamyshev_stationarity(fixture_dir,fullfile(output_dir,'stationarity_fixture_analysis'),fixture_dir,struct('make_figures',false));
region=analysis.rounds(1).pre_tracker.main_half_max_region;
check('periodic_main_region_and_compressed_region_from_saved_fields',region.crosses_time_boundary && ...
    region.start_index==63 && region.end_index==3 && region.sample_count==5 && ...
    region.sample_span_ps==4*dt && region.region_energy_fraction==1 && region.outside_max_to_peak_ratio==0 && ...
    analysis.endpoint_planes.compressed.main_half_max_region.crosses_time_boundary);
check('adjacent_fixed6_missing_reasons_suffix_and_prefix_rules', ...
    isnan(analysis.rounds(1).pre_tracker.previous_round.raw_relative_L2) && ...
    isnan(analysis.rounds(5).pre_tracker.fixed_round_6.aligned_relative_L2) && ...
    analysis.rounds(6).pre_tracker.fixed_round_6.aligned_relative_L2==0 && ...
    isequal(analysis.last_five_rounds_summary.rounds,2:6) && ...
    analysis.prefix_comparison.complete && analysis.prefix_comparison.all_observed_checks_passed);
check('separate_pre_post_and_spectral_shift_invariance', ...
    analysis.rounds(2).pre_tracker.previous_round.raw_relative_L2>0 && ...
    analysis.rounds(2).pre_tracker.previous_round.aligned_relative_L2==0 && ...
    analysis.rounds(2).pre_tracker.previous_round.shift_samples==-1 && ...
    analysis.rounds(2).post_tracker.previous_round.raw_relative_L2==0 && ...
    analysis.rounds(2).pre_tracker.previous_round.spectral_intensity_relative_L2<1e-12);
partial_dir=fullfile(output_dir,'stationarity_partial_fixture'); mkdir(partial_dir);
partial=MamyshevWaveforms(partial_dir,identity,design); partial.initialize(t,f,f0);
partial.round(1,sqrt(power),sqrt(power),trapz(t,power)/1000);
write_mamyshev_record(fullfile(partial_dir,'final_result.json'), ...
    mamyshev_result_record(struct(),struct('job_status','timeout','stop_reason','external_timeout'),provenance));
partial_report=analyze_mamyshev_stationarity(partial_dir,fullfile(output_dir,'stationarity_partial_analysis'),fixture_dir,struct('make_figures',false));
check('timeout_partial_remains_diagnostic_with_missing_endpoint',partial_report.diagnostic_only && ...
    strcmp(partial_report.run_job_status,'timeout') && ~partial_report.endpoint_planes.compressed.available && ...
    ~partial_report.prefix_comparison.complete && partial_report.completed_saved_rounds==1);
empty_dir=fullfile(output_dir,'stationarity_empty_fixture'); mkdir(empty_dir);
empty=MamyshevWaveforms(empty_dir,identity,design); empty.initialize(t,f,f0);
empty_report=analyze_mamyshev_stationarity(empty_dir,fullfile(output_dir,'stationarity_empty_analysis'),'',struct('make_figures',false));
check('zero_saved_rounds_explicitly_unobserved_and_rng_unchanged', ...
    strcmp(empty_report.status,'no_saved_rounds') && empty_report.diagnostic_only && ...
    empty_report.completed_saved_rounds==0 && isequal(saved_rng,rng));
report=struct('suite','stationarity_analysis','cases',cases,'all_passed',all([cases.passed]), ...
    'fixture_kind','artificial_intensities_and_saved_fields','full_cavity_attempts',0, ...
    'propagation_executed',false,'compressor_optimization_executed',false, ...
    'physical_state','undetermined','eligible_as_validated_training_truth',false);
mamyshev_write_diagnostic(fullfile(output_dir,'stationarity_analysis_tests.json'),report);
    function check(name,passed)
        cases(end+1)=struct('name',name,'passed',passed);
        assert(passed,'StationarityTest:Assertion','%s',name);
    end
end
