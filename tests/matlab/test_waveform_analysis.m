function report=test_waveform_analysis(output_dir)
%TEST_WAVEFORM_ANALYSIS Artificial plane wave, no production propagation.
% An exact-bin negative-frequency tone has a closed-form discrete energy and
% peak. Its constant intensity deliberately is not represented as a laser pulse.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(root,'scripts')); addpath(fullfile(root,'code','ml_bridge'));
fixture_dir=fullfile(output_dir,'analysis_fixture'); mkdir(fixture_dir);
identity=struct('run_id','synthetic_analysis_fixture','source_identity',struct('fixture_version','plane_wave_v1'));
design=struct('kind','synthetic_exact_bin_plane_wave','independent_physical_design',false);
writer=MamyshevWaveforms(fixture_dir,identity,design);
N=128; dt=0.1; t=((0:N-1)-N/2)*dt; f0=2; f=f0+((0:N-1)'-N/2)/(N*dt);
A=2*exp(2i*pi*40*(0:N-1)'/N); B=A/2;
writer.initialize(t,f,f0);
E1=(N-1)*dt*4/1000; E2=E1/4;
writer.round(1,A,circshift(A,3),E1);
writer.round(2,B,circshift(B,3),E2);
legacy=struct('output_field',circshift(B,3),'pigtail_output_field',0.8*circshift(B,3), ...
    'output_energy',E2,'rt_num',2,'t',t,'f',f,'fwhm_ps',(N-1)*dt, ...
    'dechirped_fwhm_fs',123,'transform_limited_fwhm_fs',100, ...
    'dechirped_peak_power_W',2,'energy_rel_fluct',0.3,'converged',true, ...
    'force_stop',false,'pulse_survives',true,'ML_state',1);
writer.finish(legacy,sqrt(2)*circshift(B,3));
legacy.compressed_field=sqrt(2)*circshift(B,3);
legacy.waveform_artifacts=writer.summary();
provenance=struct('run_id',identity.run_id,'source_identity',identity.source_identity, ...
    'physics_identity_id','synthetic_waveform_analysis_fixture', ...
    'numerical_version','fixture_not_a_backend_run','source_kind','synthetic_component_fixture');
candidate=mamyshev_result_record(legacy,struct('job_status','completed'),provenance);
write_mamyshev_record(fullfile(fixture_dir,'final_result.json'),candidate);
before_rng=rng;
analysis=analyze_mamyshev_waveforms(fixture_dir,fullfile(output_dir,'analysis_fixture_output'), ...
    fullfile(fixture_dir,'final_result.json'));
cases=struct('name',{},'passed',{});
check('closed_form_energy_peak_and_global_sample_width', ...
    abs(analysis.rounds(1).pre_tracker.energy_trapz_nJ-E1)<1e-14 && ...
    abs(analysis.rounds(1).pre_tracker.energy_periodic_sum_nJ-N*dt*4/1000)<1e-14 && ...
    abs(analysis.rounds(1).pre_tracker.peak_power_W-4)<1e-14 && ...
    abs(analysis.rounds(1).pre_tracker.global_half_max_span_ps-(N-1)*dt)<1e-13);
check('discrete_Parseval_and_contract_scalar_comparisons',analysis.all_recomputation_checks_passed && analysis.all_reference_checks_passed);
check('trapz_and_periodic_sums_are_distinct', ...
    abs(analysis.rounds(1).pre_tracker.energy_periodic_sum_nJ- ...
    analysis.rounds(1).pre_tracker.energy_trapz_nJ-4*dt/1000)<1e-14);
check('negative_frequency_retained_and_fixed_edge_bins', ...
    analysis.grid.negative_frequency_samples>0 && analysis.grid.edge_samples_per_side==2 && ...
    abs(analysis.rounds(1).pre_tracker.spectral_peak_frequency_THz-(-1.125))<1e-12 && ...
    abs(analysis.rounds(1).pre_tracker.spectral_peak_density_nJ_per_THz-0.65536)<1e-12 && ...
    abs(analysis.rounds(1).pre_tracker.time_left_energy_fraction-2/128)<1e-14 && ...
    abs(analysis.rounds(1).pre_tracker.time_right_energy_fraction-2/128)<1e-14);
check('round_intensity_change_without_alignment_or_normalization', ...
    abs(analysis.rounds(2).pre_intensity_relative_L2_previous.value-0.75)<1e-14 && ...
    abs(analysis.rounds(2).post_intensity_relative_L2_previous.value-0.75)<1e-14);
check('global_width_not_substituted_for_legacy_compressor_width', ...
    isnan(analysis.compressor_local_width_recomputation.value) && ...
    analysis.final_planes.compressed.global_half_max_span_ps*1000~=legacy.dechirped_fwhm_fs);
check('three_png_artifacts_and_rng_unchanged',numel(analysis.figures)==3 && ...
    all(cellfun(@(x)isfile(fullfile(output_dir,'analysis_fixture_output',x)),analysis.figures)) && isequal(before_rng,rng));

% Every failing input is a NEW explicitly synthetic directory. Never touch
% a historical or real run artifact to exercise a corruption path.
bad_dir=fullfile(output_dir,'analysis_nonfinite_fixture'); copyfile(fixture_dir,bad_dir);
path=fullfile(bad_dir,'waveforms_round_0001.mat'); data=load(path); data.pre_tracker_field(5)=NaN; save(path,'-struct','data');
check('nonfinite_complex_input_rejected',expect_error(@()analyze_mamyshev_waveforms(bad_dir, ...
    fullfile(output_dir,'analysis_nonfinite_output'),'',struct('make_figures',false)),'WaveformAnalysis:NonfiniteField'));
bad_dir=fullfile(output_dir,'analysis_grid_fixture'); copyfile(fixture_dir,bad_dir);
path=fullfile(bad_dir,'waveforms_round_0001.mat'); data=load(path); data.f_THz=data.f_THz+0.01; save(path,'-struct','data');
check('inconsistent_frequency_coordinates_rejected',expect_error(@()analyze_mamyshev_waveforms(bad_dir, ...
    fullfile(output_dir,'analysis_grid_output'),'',struct('make_figures',false)),'WaveformAnalysis:FrequencyGrid'));
bad_dir=fullfile(output_dir,'analysis_units_fixture'); copyfile(fixture_dir,bad_dir);
path=fullfile(bad_dir,'waveforms_round_0001.mat'); data=load(path); data.metadata.units.t='fs'; save(path,'-struct','data');
check('wrong_time_units_rejected',expect_error(@()analyze_mamyshev_waveforms(bad_dir, ...
    fullfile(output_dir,'analysis_units_output'),'',struct('make_figures',false)),'WaveformAnalysis:Units'));
report=struct('suite','waveform_analysis','fixture_kind',design.kind,'cases',cases, ...
    'all_passed',all([cases.passed]),'propagation_executed',false,'full_cavity_attempts',0, ...
    'compressor_optimization_executed',false,'physical_state','undetermined', ...
    'eligible_as_validated_training_truth',false);
mamyshev_write_diagnostic(fullfile(output_dir,'waveform_analysis_tests.json'),report);
    function check(name,passed)
        cases(end+1)=struct('name',name,'passed',passed);
        assert(passed,'WaveformAnalysisTest:Assertion','%s',name);
    end
end
function yes=expect_error(fn,identifier)
yes=false;
try, fn(); catch exception, yes=strcmp(exception.identifier,identifier); end
end
