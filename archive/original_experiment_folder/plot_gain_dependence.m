%% ---------------------------------------------------------
%  Gain fiber length 数据
%% ---------------------------------------------------------
Lg_m = [2.5,2.8, 3.2,3.6, 4.0,4.4, 4.8,5.2, 5.6];

% 能量（nJ）
Energy_Lg_nJ = [70.0,76.5, 82.0,89.0, 92.3,97.0, 103.0,108.0, 113.0];

% 脉宽（fs）
FWHM_Lg_fs = [55.0,52.5, 50.0,48.2, 45.0,43.0, 42.0,41.4, 40.0];

% 峰值功率（MW）≈ Energy / FWHM
Ppeak_Lg_MW = Energy_Lg_nJ ./ FWHM_Lg_fs;

% 输出中心波长（nm）
lambda_Lg_nm = [1030.4,1030, 1030.5,1030, 1030.7,1030, 1030.8,1030, 1030.9];


%% ---------------------------------------------------------
%  统一画图风格参数
%% ---------------------------------------------------------
fontname = 'Times New Roman';
axFont   = 14;
labFont  = 16;
titleFont = 17;
lw = 1.8;
ms = 4;

% 统一颜色
colBlue   = [0 0.35 0.75];      % 蓝色
colOrange = [0.85 0.33 0.10];   % 橙色


%% ---------------------------------------------------------
%  图 1：Energy + Peak Power vs Gain length
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

yyaxis left;
p1 = builtin('plot', Lg_m, Energy_Lg_nJ, 'o-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

ylabel('Pulse Energy (nJ)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([60 120]);
ax = gca;
ax.YAxis(1).Color = colBlue;

yyaxis right;
p2 = builtin('plot', Lg_m, Ppeak_Lg_MW, 's--', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colOrange, ...
    'MarkerFaceColor', colOrange);

ylabel('Peak Power (MW)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([1.0 3.0]);
ax = gca;
ax.YAxis(2).Color = colOrange;

xlabel('Gain Fiber Length (m)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Energy and Peak Power vs Gain Fiber Length', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

xlim([2.3 5.8]);
xticks(2.5:0.5:5.5);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold');

legend([p1 p2], {'Energy', 'Peak Power'}, ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northwest');

exportgraphics(gcf, 'gain_energy_peak_power.png', 'Resolution', 300);


%% ---------------------------------------------------------
%  图 2：Pulse Duration vs Gain length
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p3 = builtin('plot', Lg_m, FWHM_Lg_fs, 'd-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Gain Fiber Length (m)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('FWHM (fs)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Duration vs Gain Fiber Length', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

ylim([38 57]);
xlim([2.3 5.8]);
xticks(2.5:0.5:5.5);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p3, 'FWHM', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northeast');

exportgraphics(gcf, 'gain_pulse_duration.png', 'Resolution', 300);


%% ---------------------------------------------------------
%  图 3：Output Central Wavelength vs Gain length
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p4 = builtin('plot', Lg_m, lambda_Lg_nm, '^-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Gain Fiber Length (m)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('Output Wavelength (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Output Central Wavelength vs Gain Fiber Length', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

ylim([1030.3 1031.0]);
xlim([2.3 5.8]);
xticks(2.5:0.5:5.5);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p4, 'Central Wavelength', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'southeast');

exportgraphics(gcf, 'gain_central_wavelength.png', 'Resolution', 300);