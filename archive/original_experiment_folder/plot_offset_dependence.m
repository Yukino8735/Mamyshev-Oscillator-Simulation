%% ---------------------------------------------------------
%  Offset 数据（Pump Power = 4 W）
%% ---------------------------------------------------------
offset_nm = 4:0.5:12;

% 能量（nJ）
Energy_off_nJ = [ ...
    110.0, 109.0, 108.0, 107.3, 106.0, 103.1, 102.0, 101.5, ...
    98.0, 97.4, 95.0, 94.6, 92.3, 92.7, 100.0, 104.7, 110.0];

% 脉宽（fs）
FWHM_off_fs = [ ...
    60.0, 58.4, 58.0, 57.0, 55.0, 52.3, 52.0, 50.0, ...
    49.0, 47.6, 47.0, 46.6, 45.0, 44.8, 43.0, 42.0, 41.0];

% 峰值功率（MW）
Ppeak_off_MW = [ ...
    1.833, 1.843, 1.862, 1.883, 1.927, 1.944, 1.962, 1.973, ...
    2.000, 2.012, 2.021, 2.049, 2.130, 2.231, 2.326, 2.497, 2.683];

% 输出中心波长（nm）
lambda_out_nm = [ ...
    1035.5, 1035.0, 1034.6, 1034.0, 1033.8, 1033.0, 1032.9, 1032.1, ...
    1032.0, 1031.5, 1031.3, 1031.0, 1030.7, 1030.4, 1030.2, 1030.0, 1029.8];


%% ---------------------------------------------------------
%  统一画图风格参数
%% ---------------------------------------------------------
fontname = 'Times New Roman';
axFont   = 14;
labFont  = 16;
titleFont = 17;
lw = 1.8;
ms = 4;

% 统一颜色
colBlue   = [0 0.35 0.75];      % 蓝色
colOrange = [0.85 0.33 0.10];   % 橙色


%% ---------------------------------------------------------
%  图 1：Energy + Peak Power vs Filter Offset
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

yyaxis left;
p1 = builtin('plot', offset_nm, Energy_off_nJ, 'o-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

ylabel('Pulse Energy (nJ)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([85 120]);
ax = gca;
ax.YAxis(1).Color = colBlue;

yyaxis right;
p2 = builtin('plot', offset_nm, Ppeak_off_MW, 's--', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colOrange, ...
    'MarkerFaceColor', colOrange);

ylabel('Peak Power (MW)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([1.7 3.0]);
ax = gca;
ax.YAxis(2).Color = colOrange;

xlabel('Filter Offset (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Energy and Peak Power vs Filter Offset', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

xlim([3.5 12.5]);
xticks(4:1:12);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold');

legend([p1 p2], {'Energy', 'Peak Power'}, ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northwest');

exportgraphics(gcf, 'offset_energy_peak_power.png', 'Resolution', 300);


