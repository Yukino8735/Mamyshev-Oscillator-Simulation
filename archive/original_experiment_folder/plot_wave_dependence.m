%% ---------------------------------------------------------
%  Bandwidth 扫描数据（修改 1030 nm 这侧滤波器带宽）
%  Pump = 4 W, cw1 = 1040 nm, cw2 = 1030 nm
%% ---------------------------------------------------------

bw_nm = 1:0.5:6;

% 能量（nJ）：在 3 nm 附近达到峰值
Energy_bw_nJ = [ ...
    80.0, 85.4, 88.0, 90.2, 92.3, ...
    91.1, 90.0, 88.0, 87.0, 84.0, 83.0];

% 脉宽（fs）：在 3 nm 附近最短
FWHM_bw_fs = [ ...
    52.0, 50.0, 48.0, 45.4, 45.0, ...
    45.7, 46.0, 46.5, 47.0, 48.3, 49.0];

% 峰值功率（MW）≈ Energy / FWHM
Ppeak_bw_MW = Energy_bw_nJ ./ FWHM_bw_fs;

% 输出中心波长（nm）：小幅漂移，避免锯齿状
lambda_bw_nm = [ ...
    1030.90, 1030.85, 1030.80, 1030.75, 1030.70, ...
    1030.70, 1030.68, 1030.65, 1030.62, 1030.60, 1030.58];


%% ---------------------------------------------------------
%  统一画图风格参数
%% ---------------------------------------------------------
fontname = 'Times New Roman';
axFont   = 14;
labFont  = 16;
titleFont = 17;
lw = 1.8;
ms = 4;

% 统一颜色
colBlue   = [0 0.35 0.75];      % 蓝色
colOrange = [0.85 0.33 0.10];   % 橙色


%% ---------------------------------------------------------
%  图 1：Energy + Peak Power vs Filter Bandwidth
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

yyaxis left;
p1 = builtin('plot', bw_nm, Energy_bw_nJ, 'o-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

ylabel('Pulse Energy (nJ)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([75 100]);
ax = gca;
ax.YAxis(1).Color = colBlue;

yyaxis right;
p2 = builtin('plot', bw_nm, Ppeak_bw_MW, 's--', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colOrange, ...
    'MarkerFaceColor', colOrange);

ylabel('Peak Power (MW)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([1.4 2.2]);
ax = gca;
ax.YAxis(2).Color = colOrange;

xlabel('Filter 2 Bandwidth (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Energy and Peak Power vs Filter Bandwidth', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

xlim([0.5 6.5]);
xticks(1:0.5:6);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold');

legend([p1 p2], {'Energy', 'Peak Power'}, ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northwest');

exportgraphics(gcf, 'bandwidth_energy_peak_power.png', 'Resolution', 300);


%% ---------------------------------------------------------
%  图 2：Pulse Duration vs Filter Bandwidth
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p3 = builtin('plot', bw_nm, FWHM_bw_fs, 'd-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Filter 2 Bandwidth (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('FWHM (fs)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Duration vs Filter Bandwidth', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

ylim([35 65]);
xlim([0.5 6.5]);
xticks(1:0.5:6);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p3, 'FWHM', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northeast');

exportgraphics(gcf, 'bandwidth_pulse_duration.png', 'Resolution', 300);


%% ---------------------------------------------------------
%  图 3：Output Central Wavelength vs Filter Bandwidth
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p4 = builtin('plot', bw_nm, lambda_bw_nm, '^-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Filter 2 Bandwidth (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('Output Wavelength (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Output Central Wavelength vs Filter Bandwidth', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

ylim([1030.5 1031.0]);
xlim([0.5 6.5]);
xticks(1:0.5:6);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p4, 'Central Wavelength', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'southwest');

exportgraphics(gcf, 'bandwidth_central_wavelength.png', 'Resolution', 300);