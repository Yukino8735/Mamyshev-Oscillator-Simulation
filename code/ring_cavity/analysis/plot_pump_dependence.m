%% ---------------------------------------------------------
%  Pump Power 数据
%  These arrays are preserved historical/processed values used for the
%  thesis figures; they are not loaded from raw MAT scan files.
%% ---------------------------------------------------------
script_dir = fileparts(mfilename('fullpath'));
code_dir = fileparts(fileparts(script_dir));
addpath(code_dir);
[project_root, ~] = setup_mamyshev_project();
out_dir = fullfile(project_root, 'results', 'ring_cavity', 'generated');
if ~isfolder(out_dir)
    mkdir(out_dir);
end

Pump = 3:0.25:7;

Energy_nJ = [62.1 70.0 79.8 86.0 92.3 110 127.7 134 149.2 160 171.5 177 183.0 196 197.6 198 198.1];
FWHM_fs   = [61.4 59 58.7 50 45.0 43 42.5 42 41.3 41 40.6 40.3 40.0 38.8 38.7 38.5 38.1];
lambda_nm = [1029.9 1030 1030.2 1030 1030.7 1030 1031.0 1030 1031.4 1030 1032.0 1030 1032.5 1030 1033.3 1030 1034.1];

% 峰值功率（MW）≈ Energy / FWHM
Ppeak_MW = Energy_nJ ./ FWHM_fs;


%% ---------------------------------------------------------
%  统一画图风格参数
%% ---------------------------------------------------------
fontname = 'Times New Roman';
axFont   = 14;
labFont  = 16;
titleFont = 17;
lw = 1.8;
ms = 4;

% 统一颜色
colBlue   = [0 0.35 0.75];      % 蓝色
colOrange = [0.85 0.33 0.10];   % 橙色


%% ---------------------------------------------------------
%  图 1：Energy + Peak Power vs Pump Power
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

yyaxis left;
p1 = builtin('plot', Pump, Energy_nJ, 'o-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

ylabel('Pulse Energy (nJ)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([50 220]);
ax = gca;
ax.YAxis(1).Color = colBlue;

yyaxis right;
p2 = builtin('plot', Pump, Ppeak_MW, 's--', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colOrange, ...
    'MarkerFaceColor', colOrange);

ylabel('Peak Power (MW)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylim([0.8 6.0]);
ax = gca;
ax.YAxis(2).Color = colOrange;

xlabel('Pump Power (W)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Energy and Peak Power vs Pump Power', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

xlim([2.8 7.2]);
xticks(3:0.5:7);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold');

legend([p1 p2], {'Energy', 'Peak Power'}, ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northwest');

exportgraphics(gcf, fullfile(out_dir, 'pump_energy_peak_power.png'), 'Resolution', 300);


%% ---------------------------------------------------------
%  图 2：Pulse Duration vs Pump Power
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p3 = builtin('plot', Pump, FWHM_fs, 'd-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Pump Power (W)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('FWHM (fs)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Pulse Duration vs Pump Power', ...
    'FontName', fontname, ...
    'FontSize', titleFont, ...
    'FontWeight', 'bold');

ylim([35 65]);
xlim([2.8 7.2]);
xticks(3:0.5:7);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p3, 'FWHM', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northeast');

exportgraphics(gcf, fullfile(out_dir, 'pump_pulse_duration.png'), 'Resolution', 300);


%% ---------------------------------------------------------
%  图 3：Output Central Wavelength vs Pump Power
%% ---------------------------------------------------------
figure;
set(gcf, 'Position', [100 100 1100 420], 'Color', 'w');

p4 = builtin('plot', Pump, lambda_nm, '^-', ...
    'LineWidth', lw, ...
    'MarkerSize', ms, ...
    'Color', colBlue, ...
    'MarkerFaceColor', colBlue);

xlabel('Pump Power (W)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

ylabel('Output Wavelength (nm)', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'FontWeight', 'bold');

title('Output Central Wavelength vs Pump Power', ...
