xticks(3:0.5:7);

box on;
grid off;

set(gca, ...
    'LineWidth', 1.6, ...
    'FontName', fontname, ...
    'FontSize', axFont, ...
    'FontWeight', 'bold', ...
    'YColor', colBlue);

legend(p4, 'Central Wavelength', ...
    'FontName', fontname, ...
    'FontSize', labFont, ...
    'Location', 'northwest');

exportgraphics(gcf, fullfile(out_dir, 'pump_central_wavelength.png'), 'Resolution', 300);
