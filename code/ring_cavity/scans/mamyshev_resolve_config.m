function [config,resolved] = mamyshev_resolve_config(config)
% Four design inputs, in W/nm/nm/m. No validated physical domain is implied.
% The legacy engine requires length/save_period integral to within one eps;
% preserve that check without rounding the requested length or changing dz.
defaults=struct('pump_power_W',4,'filter_offset_nm',10,'filter2_bw_nm',3,'gain_length_m',4);
if nargin==0, config=defaults; end
assert(isstruct(config) && isscalar(config), ...
    'MamyshevConfig:InvalidType','Expected one scalar four-dimensional configuration struct.');
names=fieldnames(defaults);
assert(isequal(sort(fieldnames(config)),sort(names)), ...
    'MamyshevConfig:Fields','Exactly pump_power_W, filter_offset_nm, filter2_bw_nm, gain_length_m are required; cw2 is not an independent input.');
for k=1:numel(names)
    value=config.(names{k});
    assert(isnumeric(value) && ~islogical(value) && isscalar(value) && isreal(value) && isfinite(value), ...
        'MamyshevConfig:FiniteReal','%s must be one finite real numeric value in its named unit.',names{k});
    config.(names{k})=double(value);
end
assert(config.pump_power_W>=0,'MamyshevConfig:Pump','Pump power must be nonnegative W.');
assert(config.filter2_bw_nm>0,'MamyshevConfig:Bandwidth','Filter bandwidth must be positive nm.');
assert(1040-config.filter_offset_nm>0,'MamyshevConfig:Wavelength','SF2 center 1040-offset must be positive nm.');
assert(config.gain_length_m>0,'MamyshevConfig:Length','Gain length must be positive m.');
ratio=config.gain_length_m/0.1;
assert(isfinite(ratio) && ratio>=1 && ~(rem(ratio,1) && rem(ratio+eps(ratio),1) && rem(ratio-eps(ratio),1)), ...
    'MamyshevConfig:SaveGrid','Gain length must cover at least one unchanged 0.1 m save interval and be grid-compatible; requested length is not rounded.');
resolved=struct('units',struct('pump_power_W','W','filter_offset_nm','nm', ...
    'filter2_bw_nm','nm','gain_length_m','m'), ...
    'offset_definition','SF1 center minus SF2 center', ...
    'sf1_center_nm',1040,'sf2_center_nm',1040-config.filter_offset_nm, ...
    'passive_lengths_m',[0.4 1.5 3.2],'pigtail_length_m',0.2, ...
    'cavity_length_m',sum([config.gain_length_m 0.4 1.5 3.2]), ...
    'matches_historical_reference',isequal(config,defaults), ...
    'domain_status','Input legality only; no four-dimensional physical domain has been validated.');
end
