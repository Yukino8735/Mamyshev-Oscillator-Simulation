classdef MamyshevWaveforms < handle
    % Bounded read-only field evidence. No propagation, RNG, or recovery logic.
    % A record is a completed round at the SF1 rejected port, not a design row.
    properties (SetAccess=private)
        output_dir
        identity
        design_config
        initialized=false
        finalized=false
        t_ps=[]
        f_THz=[]
        f0_THz=[]
        raw_energy_history=[]
        rounds=struct('roundtrip',{},'path',{},'raw_energy_nJ',{}, ...
            'field_size',{},'finite',{},'bytes',{},'sha256',{})
        final=[]
    end
    methods
        function self=MamyshevWaveforms(output_dir,identity,design_config)
            assert(isfolder(output_dir),'MamyshevWaveforms:Directory','Directory must already exist.');
            assert(isstruct(identity) && isscalar(identity) && ...
                isfield(identity,'run_id') && isfield(identity,'source_identity') && ...
                ~isempty(identity.run_id) && ~isempty(identity.source_identity), ...
                'MamyshevWaveforms:Identity','Explicit run and source identities are required.');
            assert(isstruct(design_config) && isscalar(design_config), ...
                'MamyshevWaveforms:Configuration','Explicit design configuration is required.');
            assert(isempty(dir(fullfile(output_dir,'waveforms_*.mat*'))) && ...
                isempty(dir(fullfile(output_dir,'waveform_manifest.json*'))), ...
                'MamyshevWaveforms:ExistingRecord','Refusing existing waveform evidence.');
            self.output_dir=output_dir; self.identity=identity; self.design_config=design_config;
        end

        function initialize(self,t,f,f0)
            assert(~self.initialized && ~self.finalized,'MamyshevWaveforms:State','Already initialized.');
            assert(isnumeric(t) && isreal(t) && isvector(t) && numel(t)>=2 && ...
                all(isfinite(t(:))) && all(diff(t(:))>0), ...
                'MamyshevWaveforms:Grid','Time must be a finite increasing ps vector.');
            assert(isnumeric(f) && isreal(f) && isvector(f) && numel(f)==numel(t) && ...
                all(isfinite(f(:))) && all(diff(f(:))>0) && isnumeric(f0) && ...
                isscalar(f0) && isreal(f0) && isfinite(f0) && f0>0, ...
                'MamyshevWaveforms:Grid','Absolute frequency must be finite increasing THz.');
            dt=t(2)-t(1); n=numel(t);
            assert(max(abs(diff(t(:))-dt))<=64*eps(max(1,max(abs(t(:))))), ...
                'MamyshevWaveforms:Grid','Time grid must be uniform.');
            expected=f0+((0:n-1)'-floor(n/2))/(n*dt);
            assert(max(abs(f(:)-expected))<=64*eps(max(abs(expected))), ...
                'MamyshevWaveforms:Grid','Frequency grid must use f0 plus centered FFT offsets.');
            self.t_ps=t; self.f_THz=f; self.f0_THz=f0; self.initialized=true;
            self.flush(false);
        end

        function round(self,rt,pre_tracker,post_tracker,raw_energy_nJ)
            assert(self.initialized && ~self.finalized,'MamyshevWaveforms:State','Writer is not active.');
            assert(isnumeric(rt) && isscalar(rt) && isreal(rt) && isfinite(rt) && ...
                rt==numel(self.rounds)+1,'MamyshevWaveforms:Round','Rounds must be consecutive from one.');
            self.validate_field(pre_tracker); self.validate_field(post_tracker);
            assert(isequal(size(pre_tracker),size(post_tracker)), ...
                'MamyshevWaveforms:Field','Tracker must preserve field dimensions.');
            assert(isnumeric(raw_energy_nJ) && isreal(raw_energy_nJ) && ...
                isscalar(raw_energy_nJ) && isfinite(raw_energy_nJ) && raw_energy_nJ>=0, ...
                'MamyshevWaveforms:Energy','Raw energy must be finite nonnegative nJ.');
            relative=sprintf('waveforms_round_%04d.mat',rt);
            payload=struct('pre_tracker_field',pre_tracker,'post_tracker_field',post_tracker, ...
                'roundtrip',rt,'raw_energy_nJ',raw_energy_nJ,'t_ps',self.t_ps, ...
                'f_THz',self.f_THz,'f0_THz',self.f0_THz,'metadata',self.metadata());
            self.write_mat(relative,payload);
            hash=mamyshev_artifact_integrity(self.output_dir,{relative});
            self.rounds(end+1)=struct('roundtrip',rt,'path',relative, ...
                'raw_energy_nJ',raw_energy_nJ,'field_size',size(pre_tracker),'finite',true, ...
                'bytes',hash.bytes,'sha256',hash.sha256);
            self.raw_energy_history(end+1,1)=raw_energy_nJ;
            self.flush(true);
        end

        function finish(self,result,compressed_field)
            if nargin<3, compressed_field=[]; end
            assert(self.initialized && ~self.finalized && ~isempty(self.rounds), ...
                'MamyshevWaveforms:State','No completed rounds or writer already finalized.');
            required={'output_field','pigtail_output_field','output_energy','rt_num','t','f'};
            assert(isstruct(result) && isscalar(result) && all(isfield(result,required)), ...
                'MamyshevWaveforms:Result','Actual normal-return fields and coordinates are required.');
            self.validate_field(result.output_field); self.validate_field(result.pigtail_output_field);
            assert(isequal(size(result.output_field),size(result.pigtail_output_field)), ...
                'MamyshevWaveforms:Field','Returned output planes must have the same sample/mode axes.');
            assert(isequal(result.rt_num,numel(self.rounds)) && ...
                isequal(result.t,self.t_ps) && isequal(result.f,self.f_THz) && ...
                isequal(result.output_energy,self.raw_energy_history(end)), ...
                'MamyshevWaveforms:Result','Return count, grid or raw energy differs from recorded production values.');
            last=load(fullfile(self.output_dir,self.rounds(end).path),'post_tracker_field');
            assert(isequal(result.output_field,last.post_tracker_field), ...
                'MamyshevWaveforms:Result','Final output must equal the last post-tracker field.');
            compressed_available=~isempty(compressed_field);
            if compressed_available
                self.validate_field(compressed_field);
                assert(isequal(size(compressed_field),size(result.output_field)), ...
                    'MamyshevWaveforms:Field','Compressed field must use the same sample/mode axes.');
                missing_reason='';
            else
                missing_reason='Same original compressor analysis did not return an actual compressed field.';
            end
            metadata=self.metadata();
            metadata.returned_scalar_metrics=struct();
            scalar_names={'fwhm_ps','dechirped_fwhm_fs','transform_limited_fwhm_fs', ...
                'dechirped_peak_power_W','energy_mean','energy_std','energy_rel_fluct'};
            for k=1:numel(scalar_names)
                key=scalar_names{k};
                if isfield(result,key)
                    value=result.(key);
                    assert(isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value), ...
                        'MamyshevWaveforms:Result','Present scalar metric must be finite.');
                    metadata.returned_scalar_metrics.(key)=value;
                end
            end
            metadata.compressed_field_available=compressed_available;
            metadata.compressed_field_missing_reason=missing_reason;
            payload=struct('output_field',result.output_field, ...
                'pigtail_output_field',result.pigtail_output_field,'compressed_field',compressed_field, ...
                'output_energy',result.output_energy,'rt_num',result.rt_num, ...
                'raw_energy_history',self.raw_energy_history,'t_ps',self.t_ps,'f_THz',self.f_THz, ...
                'f0_THz',self.f0_THz,'metadata',metadata);
            relative='waveforms_final.mat'; self.write_mat(relative,payload);
            hash=mamyshev_artifact_integrity(self.output_dir,{relative});
            self.final=struct('path',relative,'compressed_field_available',compressed_available, ...
                'compressed_field_missing_reason',missing_reason, ...
                'field_size',size(result.output_field),'finite',true,'bytes',hash.bytes,'sha256',hash.sha256);
            self.finalized=true; self.flush(true);
        end

        function value=paths(self)
            value=[{'waveform_manifest.json'}, {self.rounds.path}];
            if ~isempty(self.final), value{end+1}=self.final.path; end
        end

        function value=summary(self)
            value=struct('schema_version','mamyshev_waveforms_v1', ...
                'manifest_path','waveform_manifest.json','artifacts',{self.paths()}, ...
                'completed_roundtrips',numel(self.rounds),'initialized',self.initialized, ...
                'finalized',self.finalized,'final',self.final);
        end
    end
    methods (Access=private)
        function validate_field(self,value)
            assert(isnumeric(value) && ismatrix(value) && ~isempty(value) && ...
                size(value,1)==numel(self.t_ps) && all(isfinite(value(:))), ...
                'MamyshevWaveforms:Field','Field must be a finite time-by-mode complex amplitude array.');
        end

        function value=metadata(self)
            value=struct('schema_version','mamyshev_waveforms_v1', ...
                'run_id',self.identity.run_id,'source_identity',self.identity.source_identity, ...
                'design_config',self.design_config, ...
                'units',struct('field','sqrt(W)','t','ps','f','THz','f0','THz','energy','nJ','power','W'), ...
                'conventions',struct('field_axes',{{'time_sample','mode'}}, ...
                'frequency_grid','absolute f0 + centered offset, ascending', ...
                'time_to_frequency','fftshift(ifft(A,[],1),1)', ...
                'energy','trapz(abs(A).^2,1)*dt_ps/1000 nJ; modes retained separately', ...
                'raw_output_energy','original SF1 rejected pre-pulse_tracker integral; never replaced by centered-field integral'), ...
                'planes',struct('pre_tracker_field','SF1 rejected 1-H, before pulse_tracker, uncompressed', ...
                'post_tracker_field','SF1 rejected 1-H, after pulse_tracker, uncompressed', ...
                'output_field','actual returned final SF1 rejected 1-H, after pulse_tracker, before pigtail, uncompressed', ...
                'pigtail_output_field','actual returned after 0.2 m pigtail, before original compressor analysis', ...
                'compressed_field','actual dechirped field from same original compressor analysis; not transform-limited field'), ...
                'physical_state','undetermined','numerical_validation','not_verified', ...
                'eligible_as_validated_training_truth',false);
        end

        function flush(self,replace_existing)
            value=self.metadata();
            value.initialized=self.initialized; value.finalized=self.finalized;
            value.grid=struct('sample_count',numel(self.t_ps),'dt_ps',self.t_ps(2)-self.t_ps(1), ...
                'f0_THz',self.f0_THz,'time_size',size(self.t_ps),'frequency_size',size(self.f_THz));
            value.completed_roundtrips=numel(self.rounds);
            value.raw_energy_history_nJ=self.raw_energy_history; value.rounds=self.rounds; value.final=self.final;
            mamyshev_write_diagnostic(fullfile(self.output_dir,'waveform_manifest.json'),value,replace_existing);
        end

        function write_mat(self,relative,payload)
            path=fullfile(self.output_dir,relative); temporary=[path '.tmp'];
            assert(~isfile(path) && ~isfile(temporary),'MamyshevWaveforms:ExistingRecord', ...
                'Refusing to overwrite final or temporary MAT evidence.');
            % Fixed local temporary name and save -struct do not consume RNG.
            save(temporary,'-struct','payload','-v7');
            assert(~isfile(path),'MamyshevWaveforms:ExistingRecord','Final MAT now exists.');
            [ok,message]=movefile(temporary,path);
            assert(ok,'MamyshevWaveforms:Write','%s',message);
        end
    end
end
