function config=mamyshev_validate_launch_context(context)
% Read-only authorization/routing validation, also usable without propagation.
assert(isstruct(context) && isscalar(context) && strcmp(context.mode,'real'), ...
    'Mamyshev:LaunchMode','Real launcher refuses fixture mode.');
assert(~has_field_recursive(context,'test_hook') && ~has_field_recursive(context,'backend'), ...
    'Mamyshev:LaunchInjection','Real launch context refuses test hooks/backend injection.');
config=[];
if isfield(context,'live_authorization')
    live=context.live_authorization; auth=live.authorization;
    config=mamyshev_resolve_config(context.design_config);
    assert(strcmp(live.schema_version,'configured_live_v1') && isequal(live.execute_real,true) && ...
        strcmp(live.plan_hash,auth.plan_hash) && ismember(live.design_id,cellstr(auth.allowed_design_ids)) && ...
        isnumeric(auth.max_new_attempts) && isscalar(auth.max_new_attempts) && isfinite(auth.max_new_attempts) && ...
        auth.max_new_attempts>=1 && fix(auth.max_new_attempts)==auth.max_new_attempts && ...
        isnumeric(live.attempt_index) && isscalar(live.attempt_index) && isfinite(live.attempt_index) && ...
        live.attempt_index>=1 && fix(live.attempt_index)==live.attempt_index && live.attempt_index<=auth.max_new_attempts, ...
        'Mamyshev:LiveAuthorization','Plan/design/attempt lacks explicit live permission.');
    assert(isequal(config,mamyshev_resolve_config(live.selected_design)) && ...
        isequal(context.save_waveforms,true) && isequal(context.requested.plot_on,false) && ...
        context.requested.PumpPower==config.pump_power_W && context.requested.cw2==1040-config.filter_offset_nm, ...
        'Mamyshev:AuthorizedDesign','Requested and authorized design/routing disagree.');
    assert(isnumeric(context.total_wall_limit_s) && isscalar(context.total_wall_limit_s) && ...
        isfinite(context.total_wall_limit_s) && context.total_wall_limit_s>30 && ...
        context.total_wall_limit_s<=auth.per_run_timeout_s && context.total_wall_limit_s<=live.remaining_total_s_before && ...
        live.remaining_total_s_before<=auth.total_wall_limit_s && context.shutdown_and_finalization_reserve_s==30, ...
        'Mamyshev:LiveBudget','Live budget/reserve is inconsistent.');
    seed=0;if isfield(auth,'seed'),seed=auth.seed;end
    assert(isnumeric(seed) && isscalar(seed) && isfinite(seed) && seed>=0 && seed<=2^32-1 && ...
        fix(seed)==seed && isequal(context.seed,seed),'Mamyshev:LiveSeed','Invalid seed routing.');
    protocol=struct('mode','legacy');if isfield(auth,'observation_protocol'),protocol=auth.observation_protocol;end
    if strcmp(protocol.mode,'legacy')
        assert(~isfield(context,'observation_options'),'Mamyshev:LiveObservation','Legacy protocol may not inject observation options.');
    else
        options=mamyshev_observation_options(context.observation_options);
        assert(strcmp(options.observation_mode,protocol.mode) && options.observation_roundtrips==protocol.roundtrips, ...
            'Mamyshev:LiveObservation','Authorized observation protocol differs from request.');
    end
else
    if isfield(context,'design_config')
        config=mamyshev_resolve_config(context.design_config);
        assert(isequal(config,mamyshev_resolve_config()) && context.seed==0 && ...
            context.requested.PumpPower==config.pump_power_W && context.requested.cw2==1040-config.filter_offset_nm && ...
            isequal(context.requested.plot_on,false) && isequal(context.save_waveforms,true), ...
            'Mamyshev:AuthorizedDesign','Historical batch authorizes only its default design.');
    else
        assert(context.seed==0 && context.requested.PumpPower==4 && context.requested.cw2==1030 && ...
            isequal(context.requested.plot_on,false),'Mamyshev:LegacyInputs','Only frozen historical inputs authorized.');
    end
    if isfield(context,'observation_options')
        options=mamyshev_observation_options(context.observation_options);
        assert(strcmp(context.batch_id,'observation_validation_001') && strcmp(context.run_id,'observation_001') && ...
            context.total_wall_limit_s==3600 && strcmp(options.observation_mode,'fixed_roundtrips') && ...
            options.observation_roundtrips==20 && isfield(context,'design_config'), ...
            'Mamyshev:ObservationAuthorization','Unexpected historical observation protocol.');
    end
end
end

function yes=has_field_recursive(value,name)
yes=false;
if isstruct(value)
    if isfield(value,name),yes=true;return;end
    fields=fieldnames(value);
    for k=1:numel(value)
        for j=1:numel(fields)
            if has_field_recursive(value(k).(fields{j}),name),yes=true;return;end
        end
    end
elseif iscell(value)
    for k=1:numel(value),if has_field_recursive(value{k},name),yes=true;return;end,end
end
end
