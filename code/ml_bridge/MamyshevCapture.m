classdef MamyshevCapture < handle
    % Read-only actual-entry snapshots. No solver decisions, RNG or full history.
    properties (SetAccess=private)
        observer
        output_dir
        context
        initialization_observed=false
        comparison_passed=false
        calls={}
        compressor=[]
        completed_roundtrips=NaN
        backend_returned=false
        source_kind='repaired_original_backend'
        gain_array_reference={}
        artifact_integrity=struct('path',{},'sha256',{},'bytes',{})
        waveforms=[]
        filter_calls={}
        observation_options=[]
        observation_history=struct('roundtrip',{},'converged',{},'force_stop_convergence',{}, ...
            'force_stop_fluctuation',{},'criterion_reason',{},'stop_reason',{})
        observation_first_legacy_convergence_roundtrip=NaN
    end
    methods
        function self=MamyshevCapture(output_dir,context)
            assert(isfolder(output_dir),'Mamyshev:Diagnostics','Output directory must already exist.');
            self.output_dir=output_dir; self.context=context;
            physics_identity='legacy_ring_phase1_v1'; numerical_version='repair_001_h01_h04';
            if isfield(context,'design_config'), physics_identity='ring_legacy_rules_config_v1'; end
            if startsWith(context.mode,'synthetic')
                physics_identity='synthetic_observer_fixture';
                numerical_version='synthetic_fixture_not_a_backend_run';
                self.source_kind='synthetic_observer_component_fixture';
            end
            self.observer=MamyshevObserver(fullfile(output_dir,'runtime_observer.json'), ...
                struct('run_id',context.run_id,'source_identity',context.source_identity));
            requested=struct('level','A','status','observed', ...
                'capture_location','explicit launch caller, before run_mamyshev initialization', ...
                'captured_utc',self.utc(),'source','actual wrapper inputs and launcher source manifest', ...
                'units',struct('PumpPower','W','cw2','nm','seed','dimensionless'), ...
                'context',context,'run_id',context.run_id,'source_identity',context.source_identity, ...
                'physics_identity_id',physics_identity,'source_kind',self.source_kind, ...
                'numerical_version',numerical_version, ...
                'wrapper_version','launchprep_001_observability', ...
                'result_protocol_version','safe_result_v1', ...
                'observer_version',self.observer.version,'rng_at_request',rng);
            mamyshev_write_diagnostic(fullfile(output_dir,'requested.json'),requested);
            self.flush();
        end

        function configuration(self,phase1_config,gain_param,prop_output,t,f,lambda,N_total_computed,pulse_death_energy,design_config,observation_options)
            assert(~self.initialization_observed,'Mamyshev:Diagnostics','Initialization captured twice.');
            for k=1:numel(phase1_config.sim_cavity)
                value=phase1_config.sim_cavity(k);
                assert(~isfield(value.adaptive_deltaZ,'test_hook'), ...
                    'Mamyshev:ActiveTestHook','Real diagnostics refuse any test_hook field, including []/false.');
            end
            actual=struct('phase1_config',phase1_config,'gain_param',{gain_param}, ...
                'prop_output',prop_output,'t',t,'f',f,'lambda',lambda);
            self.gain_array_reference=gain_param(2:5);
            root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
            resolved_functions=struct();
            expected={'GMMNLSE_propagate','code/simulation_engine/GMMNLSE/GMMNLSE_propagate.m'; ...
                'load_default_GMMNLSE_propagate','code/simulation_engine/GMMNLSE/load_default_GMMNLSE_propagate.m'; ...
                'gain_info','code/simulation_engine/GMMNLSE/gain_info.m'; ...
                'build_MMgaussian','code/simulation_engine/GMMNLSE/build_MMgaussian.m'; ...
                'gaussian_spectral_filter','code/simulation_engine/GMMNLSE/gaussian_spectral_filter.m'; ...
                'analyze_field','code/simulation_engine/GMMNLSE/analyze_field.m'; ...
                'GMMNLSE_adaptive_rategain','code/simulation_engine/GMMNLSE/Gain_rate_eqn/GMMNLSE_adaptive_rategain.m'};
            for k=1:size(expected,1)
                resolved_functions.(expected{k,1})=which(expected{k,1});
                assert(strcmp(resolved_functions.(expected{k,1}),fullfile(root,expected{k,2})), ...
                    'Mamyshev:WrongFunctionPath','Unexpected function resolution: %s.',expected{k,1});
            end
            reference=fullfile(root,'reports','local','phase1','baseline_001','configuration.mat');
            if isfield(self.context,'design_config')
                requested_config=mamyshev_resolve_config(self.context.design_config);
                assert(nargin>=10 && isequal(requested_config,design_config), ...
                    'Mamyshev:ConfigurationMismatch','Requested and production-resolved four-dimensional inputs differ.');
                comparison=mamyshev_compare_configuration(actual,reference,design_config);
            else
                comparison=mamyshev_compare_configuration(actual,reference);
            end
            comparison.run_id=self.context.run_id;
            comparison.source_identity=self.context.source_identity;
            snapshot_path=fullfile(self.output_dir,'configuration.mat');
            assert(~isfile(snapshot_path),'MamyshevRecord:ExistingRecord','Configuration exists.');
            % Arrays saved once. This is the original field/grid/gain data, no resampling.
            save(snapshot_path,'phase1_config','gain_param','prop_output','t','f','lambda', ...
                'N_total_computed','pulse_death_energy','-v7');
            fibers=phase1_config.fiber_cavity;
            meta=struct('level','B','status','observed','captured_utc',self.utc(), ...
                'run_id',self.context.run_id,'source_identity',self.context.source_identity, ...
                'capture_location','run_mamyshev after gain_info and N_total override, before first propagation', ...
                'source','actual production locals; configuration.mat','resolved_functions',resolved_functions, ...
                'propagation_started',false,'configuration',phase1_config, ...
                'gain_info_computed_N_total',N_total_computed, ...
                'final_N_total',gain_param{5},'pulse_death_energy_nJ',pulse_death_energy, ...
                'declared_MFD_um',[fibers.MFD],'actual_SR_m_minus2',[fibers.SR], ...
                'actual_effective_area_m2',1./[fibers.SR],'actual_gain_Aeff_m2',[fibers.gain_Aeff], ...
                'initial_field',self.array_summary(prop_output.fields,'sqrt(W) complex time-domain amplitude'), ...
                'time_grid',self.array_summary(t,'ps'),'frequency_grid',self.array_summary(f,'THz'), ...
                'wavelength_grid',self.array_summary(lambda,'nm'), ...
                'units',struct('fiber_lengths','m','MFD','um','SR','m^-2','gain_Aeff','m^2', ...
                'N_total','ions/um^3','field','sqrt(W)','t','ps','f','THz','lambda','nm', ...
                'gain_cross_sections','um^2 (gain_info source)','power','W','energy','nJ'), ...
                'runtime_C_status','deferred_to_authorized_run', ...
                'array_reference','configuration.mat','comparison_reference','configuration_comparison.json');
            if isfield(self.context,'design_config')
                [~,resolved]=mamyshev_resolve_config(design_config);
                meta.design_config=design_config;
                meta.model_rules=struct('model_rules_id','ring_legacy_rules_config_v1', ...
                    'historical_reference_id','legacy_ring_phase1_v1', ...
                    'matches_historical_reference',resolved.matches_historical_reference, ...
                    'H02_status','unresolved','passive_declared_MFD_um',fibers(2).MFD, ...
                    'passive_SR_derived_MFD_um',5.95, ...
                    'passive_actual_SR_m_minus2',fibers(2).SR, ...
                    'passive_actual_area_m2',1/fibers(2).SR, ...
                    'passive_lengths_m',[fibers(2:4).L0], ...
                    'pigtail_length_m',phase1_config.output_fiber_length_m, ...
                    'N_total_override',gain_param{5},'output_port','1-H','filter_order',4);
            end
            if isfield(self.context,'observation_options')
                requested_observation=mamyshev_observation_options(self.context.observation_options,phase1_config.max_rt);
                assert(nargin>=11 && isequal(observation_options,requested_observation), ...
                    'Mamyshev:ObservationMismatch','Requested and actually resolved observation protocols differ.');
                self.observation_options=observation_options;
                meta.observation_options=observation_options;
            end
            mamyshev_write_diagnostic(fullfile(self.output_dir,'configuration.json'),meta);
            mamyshev_write_diagnostic(fullfile(self.output_dir,'configuration_comparison.json'),comparison);
            self.initialization_observed=true; self.comparison_passed=comparison.passed; self.flush();
            assert(comparison.passed,'Mamyshev:ConfigurationMismatch', ...
                'Actual initialization differs from directly captured baseline_001; inspect comparison, no propagation.');
            if isfield(self.context,'save_waveforms') && self.context.save_waveforms
                assert(isfield(self.context,'design_config'),'Mamyshev:WaveformContext','Explicit design required.');
                self.waveforms=MamyshevWaveforms(self.output_dir, ...
                    struct('run_id',self.context.run_id,'source_identity',self.context.source_identity),design_config);
                self.waveforms.initialize(t,f,phase1_config.sim_cavity(1).f0);
            end
        end

        function observation_round(self,entry)
            assert(~isempty(self.observation_options) && entry.roundtrip==numel(self.observation_history)+1, ...
                'Mamyshev:ObservationSequence','Actual completed observations must be consecutive.');
            self.observation_history(end+1)=entry;
            if isnan(self.observation_first_legacy_convergence_roundtrip) && ...
                    (entry.converged || entry.force_stop_convergence)
                self.observation_first_legacy_convergence_roundtrip=entry.roundtrip;
            end
            self.flush();
        end

        function filter_call(self,rt,id,cw,bw,order,plot_on)
            if ~isfield(self.context,'design_config'), return; end
            self.filter_calls{end+1}=struct('roundtrip',rt,'filter_id',id,'cw_nm',cw, ...
                'bw_nm',bw,'order',order,'plot_on',logical(plot_on),'captured_utc',self.utc());
            self.flush();
        end

        function propagation_call(self,rt,id,fiber,initial,sim,gain_param)
            assert(~isfield(sim.adaptive_deltaZ,'test_hook'), ...
                'Mamyshev:ActiveTestHook','Active test_hook is forbidden in a real cavity invocation.');
            if isfield(sim,'readonly_observer'), sim=rmfield(sim,'readonly_observer'); end
            if sim.gain_model==4, kind='gain'; else, kind='passive'; end
            if isempty(gain_param)
                gain_rate=[]; gain_arrays_match=[];
            else
                gain_rate=gain_param{1};
                if isempty(self.gain_array_reference) && startsWith(self.context.mode,'synthetic')
                    fixture_reference=load(fullfile(self.output_dir,'configuration.mat'),'gain_param');
                    self.gain_array_reference=fixture_reference.gain_param(2:5);
                end
                gain_arrays_match=isequaln(gain_param(2:5),self.gain_array_reference);
                assert(gain_arrays_match,'Mamyshev:RuntimeParameterMismatch', ...
                    'Actual gain array arguments differ from the referenced initialization data.');
            end
            entry=struct('level','C','status','observed','captured_utc',self.utc(), ...
                'capture_location','run_mamyshev immediately before actual GMMNLSE_propagate call', ...
                'source','actual fiber/sim/gain_param call arguments; no substituted defaults', ...
                'source_kind',self.source_kind, ...
                'roundtrip',rt,'segment_id',id,'kind',kind,'fiber',fiber,'sim',sim, ...
                'gain_rate_eqn',gain_rate,'gain_arrays_reference','configuration.mat: gain_param{2:5}', ...
                'gain_arrays_match_reference',gain_arrays_match, ...
                'dt_ps',initial.dt,'input_field_size',[size(initial.fields,1),size(initial.fields,2)], ...
                'units',struct('length','m','step','m','dt','ps','power','W','t_rep','s'), ...
                'effective_runtime_defaults','recorded separately by engine in runtime_observer.json');
            if isempty(gain_param), entry.gain_arrays_reference='not passed (pigtail passive call)'; end
            self.calls{end+1}=entry;
            self.observer.begin_segment(rt,id,kind,struct('call_record_index',numel(self.calls)));
            self.flush();
        end

        function compressor_call(self,t,f,field,type,angle,spacing,plot_on)
            self.compressor=struct('level','C','status','observed','captured_utc',self.utc(), ...
                'capture_location','run_mamyshev immediately before analyze_field', ...
                'source','arguments captured before analyze_field numerical execution, pigtail output plane', ...
                'source_kind',self.source_kind,'analyzer_has_returned_at_capture',false, ...
                'type',type,'incident_angle_rad',angle,'grating_spacing_m',spacing,'plot_on',plot_on, ...
                't_size',size(t),'f_size',size(f),'field_size',size(field), ...
                'units',struct('t','ps','f','THz','field','sqrt(W)','angle','rad','spacing','m'), ...
                'analysis_defaults_status','analyze_field internal defaults covered by source identity; no claim of runtime observation');
            self.flush();
        end

        function finish(self,rt)
            self.completed_roundtrips=rt; self.backend_returned=true; self.flush();
            % Hash only after normal backend return and the last observer/call
            % flush. No hashing at propagation steps or preflight initialization.
            paths={'requested.json','configuration.mat','configuration.json', ...
                'configuration_comparison.json','runtime_calls.json','runtime_observer.json'};
            if ~isempty(self.waveforms), paths=[paths self.waveforms.paths()]; end
            self.artifact_integrity=mamyshev_artifact_integrity(self.output_dir,paths);
        end
        function abort(self,reason)
            self.observer.abort_segment(reason); self.flush();
        end
        function result=summary(self)
            counts=self.observer.summary();
            expected_artifact_count=6;
            if ~isempty(self.waveforms), expected_artifact_count=6+numel(self.waveforms.paths()); end
            result=struct('observer_version',self.observer.version, ...
                'initialization_observed',self.initialization_observed, ...
                'configuration_comparison_passed',self.comparison_passed, ...
                'runtime_call_count',numel(self.calls),'compressor_call_observed',~isempty(self.compressor), ...
                'backend_returned',self.backend_returned,'completed_roundtrips',self.completed_roundtrips, ...
                'counts_complete',counts.counts_complete, ...
                'runtime_resolved_complete',counts.runtime_resolved_complete, ...
                'artifact_integrity',self.artifact_integrity, ...
                'required_records_complete',self.initialization_observed && self.comparison_passed && ...
                self.backend_returned && counts.counts_complete && counts.runtime_resolved_complete && ...
                numel(self.calls)==4*self.completed_roundtrips+1 && ~isempty(self.compressor) && ...
                numel(self.artifact_integrity)==expected_artifact_count, ...
                'artifacts',{{'requested.json','configuration.mat','configuration.json', ...
                'configuration_comparison.json','runtime_calls.json','runtime_observer.json'}});
            if ~isempty(self.waveforms)
                result.waveform_artifacts=self.waveforms.summary();
                result.artifacts=[result.artifacts self.waveforms.paths()];
                result.required_records_complete=result.required_records_complete && self.waveforms.summary().finalized;
            end
        end
    end
    methods (Access=private)
        function flush(self)
            if isempty(self.calls), call_status='deferred_to_authorized_run'; else, call_status='observed'; end
            if isempty(self.compressor), compressor_status='deferred_to_authorized_run'; else, compressor_status='observed'; end
            value=struct('level','C','source','actual production callsites and separate engine observer', ...
                'run_id',self.context.run_id,'source_identity',self.context.source_identity, ...
                'updated_utc',self.utc(),'segment_calls_status',call_status,'segment_calls',{self.calls}, ...
                'compressor_status',compressor_status,'compressor_call',self.compressor, ...
                'runtime_defaults_artifact','runtime_observer.json','backend_returned',self.backend_returned);
            if isfield(self.context,'design_config'), value.filter_calls=self.filter_calls; end
            if ~isempty(self.observation_options)
                value.observation_options=self.observation_options;
                value.observation_history=self.observation_history;
                value.observation_first_legacy_convergence_roundtrip=self.observation_first_legacy_convergence_roundtrip;
            end
            mamyshev_write_diagnostic(fullfile(self.output_dir,'runtime_calls.json'),value,true);
        end
    end
    methods (Static, Access=private)
        function value=utc()
            value=char(datetime('now','TimeZone','UTC','Format',"yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
        end
        function value=array_summary(array,unit)
            value=struct('size',size(array),'class',class(array),'is_complex',~isreal(array), ...
                'finite',all(isfinite(array(:))),'max_abs',max(abs(array(:))),'unit',unit);
        end
    end
end
